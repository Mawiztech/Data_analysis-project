-- . FInancial Summaries

CREATE OR REPLACE VIEW financial_summary AS
WITH summary_metric AS(
      SELECT
      SUM(si.quantity * si.unit_price) AS total_revenue,
	  SUM(si.quantity * si.unit_cost) AS total_cost,
	  SUM(si.discount) AS total_discount
FROM sale_items AS si
)
SELECT
	-- Net Revenue(Total Revenue - Total Discount)
	ROUND((total_revenue - total_discount)::numeric,2) AS "Net Revenue",
	-- Gross Profit (Net Revenue - Cost)
	ROUND((total_revenue - total_discount - total_cost)::numeric,2) AS "Gross Profit",
	-- Gross Margin Profit % (Gross Profit/Net Revenue *100)
	ROUND(
       ((total_revenue - total_discount - total_cost)
	   /(total_revenue -total_discount) *100)::numeric,2
	) AS "Gross Msrgin Percentage"
FROM summary_metric;




-- . Monthly Perfoomance by Net Revenue and Gross Profit

CREATE OR REPLACE VIEW monthly_financial_trends AS
-- Aggregate raw baseline transactions into basic monthly financial units.
WITH monthly_trend AS (
	SELECT
		DATE_TRUNC('month', s.sale_date) AS sale_month,
		SUM(si.quantity * si.unit_price) AS monthly_revenue,
		SUM(si.quantity * si.unit_cost) AS monthly_cost,
		SUM(si.discount) AS monthly_discount
	FROM sales AS s
	JOIN sale_items AS si ON s.sale_id = si.sale_id
	GROUP BY DATE_TRUNC('month', s.sale_date)
),
 -- Derive net metrics from Step 1 aggregates

net_summary AS (
    SELECT 
        sale_month,
        ROUND((monthly_revenue - monthly_discount)::numeric, 2) AS monthly_net_revenue,
        ROUND((monthly_revenue - monthly_discount - monthly_cost)::numeric, 2) AS gross_monthly_profit
    FROM monthly_trend
)

-- Apply window functions to compute chronological Month-over-Month (MoM) variances
SELECT 
	TO_CHAR(sale_month, 'YYYY-MM') AS "Monthly Trend",
	monthly_net_revenue,
	gross_monthly_profit,
	ROUND((monthly_net_revenue - LAG(monthly_net_revenue) OVER (ORDER BY sale_month))::numeric, 2) AS net_revenue_MoM_change,
	ROUND((gross_monthly_profit - LAG(gross_monthly_profit) OVER (ORDER BY sale_month))::numeric, 2) AS gross_profit_MoM_change
FROM net_summary
ORDER BY monthly_net_revenue DESC;


--  Most generated sales channel
CREATE OR REPLACE VIEW sales_channel_count AS
SELECT
	sales_channel,
	COUNT(sale_id) AS "Unique Sale Channel"
FROM sales
GROUP BY sales_channel;


--  Most Customers' Payment Method
CREATE OR REPLACE VIEW payment_method AS
SELECT
	payment_method,
	COUNT(sale_id) AS "Most Used Payment Method"
FROM sales
GROUP BY payment_method
ORDER BY "Most Used Payment Method" DESC;
	

--  Performace by Branch and Region
DROP VIEW IF EXISTS regional_branch_contribution;
CREATE OR REPLACE VIEW regional_branch_contribution AS
WITH regional_summary AS(
SELECT
	-- b.branch_name,
	b.region AS "Regional Contribution",
	-- s.sales_channel AS "Sales Channel",
	SUM(si.quantity * si.unit_price) AS total_revenue,
	SUM(si.quantity * si.unit_cost) AS total_cost,
	SUM(si.discount) AS total_discount
	FROM sales AS s
	JOIN branches AS b ON s.branch_id = b.branch_id
	JOIN sale_items si ON s.sale_id = si.sale_id
	GROUP BY b.region
	
	)
	SELECT
	-- branch_name,
	"Regional Contribution",
	ROUND((total_revenue - total_discount)::numeric,2) AS "Net Revenue",
	ROUND((total_revenue - total_discount - total_cost)::numeric,2) AS "Gross Profit"
	FROM regional_summary
	ORDER BY "Gross Profit" DESC;


	
-- PRODUCT ANALYSIS AND INVENTORY LOGISTICS
--  Top 10 Best-Selling Products by Net-Revenue and Gross-Profit
CREATE OR REPLACE VIEW top_10_products AS
WITH top_selling_product AS(
SELECT
	p.product_name AS "Product Name",
	SUM(si.quantity * si.unit_price) AS total_revenue,
	SUM(si.quantity * si.unit_cost) AS total_cost,
	SUM(si.discount) AS total_discount
FROM sale_items AS si
JOIN products AS p ON si.product_id = p.product_id
GROUP BY p.product_id, p.product_name

)
SELECT
	"Product Name",
	ROUND((total_revenue - total_discount)::numeric,2) AS "Net Revenue",
	ROUND((total_revenue - total_discount - total_cost)::numeric,2) AS "Gross Profit"
FROM top_selling_product
ORDER BY "Gross Profit" DESC
LIMIT 10;


-- Product Stockout Alert and Reorder Analysis
CREATE OR REPLACE VIEW inventory_stockout_alert AS
SELECT
	b.branch_name,
	p.product_name,
	i.closing_stock,
	p.reorder_level,
	CASE
		WHEN i.closing_stock <= 15 THEN 'CRITICAL REORDER ALERT'
		WHEN i.closing_stock <= p.reorder_level THEN 'REORDER ALERT'
		ELSE 'STOCK LEVEL STABLE'
	END AS "Operational Status"
FROM inventory AS i
JOIN branches AS b ON i.branch_id = b.branch_id
JOIN products AS p ON i.product_id = p.product_id
WHERE i.stockout_flag = 'yes' OR i.closing_stock <= 15;


-- Net Revenue and Gross Profit Generated by Employee
CREATE OR REPLACE VIEW employee_production AS
WITH employee_performance AS (
SELECT
	e.employee_name AS "Employee Name",
	e.job_role AS "Job Role",
	SUM(si.quantity * si.unit_price) AS total_revenue,
	SUM(si.quantity * si.unit_cost) AS total_cost,
	SUM(si.discount) AS total_discount
FROM employees AS e
JOIN sales AS s ON e.employee_id = s.employee_id
JOIN sale_items AS si ON s.sale_id = si.sale_id
GROUP BY e.employee_name, e.job_role
	
)
SELECT
	"Employee Name",
	"Job Role",
	ROUND((total_revenue - total_discount)::numeric,2) AS "Net Revenue",
	ROUND((total_revenue - total_discount - total_cost)::numeric,2) AS "Gross Profit"
FROM employee_performance
ORDER BY "Gross Profit" DESC
LIMIT 10;


-- Inactive Customer Analysis
CREATE OR REPLACE VIEW inactive_customers AS
SELECT
	c.customer_id,
	c.first_name || '  ' || c.last_name AS "Customer Fullname",
MAX(s.sale_date) AS "Final Purchase Date"
FROM customers AS c
LEFT JOIN sales AS s ON c.customer_id = s.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name
HAVING MAX(s.sale_date) < CURRENT_DATE - INTERVAL '50 days' OR MAX(s.sale_date) IS NULL;




-- Customer Segmentation Analysis
CREATE OR REPLACE VIEW customer_concentration AS

WITH segmentation_metrix AS (
SELECT
	c.customer_segment AS "Customer Segment",
	SUM(si.quantity * si.unit_price) AS total_revenue,
	SUM(si.quantity * si.unit_cost) AS total_cost,
	SUM(si.discount) AS total_discount
FROM customers AS c
JOIN sales AS s ON c.customer_id = s.customer_id
JOIN sale_items AS si ON s.sale_id = si.sale_id
GROUP BY c.customer_segment
)

SELECT
	 "Customer Segment",
	 ROUND((total_revenue - total_discount)::numeric,2) AS "Net Revenue",
	 ROUND((total_revenue - total_discount - total_cost)::numeric,2) AS "Gross Profit"
FROM segmentation_metrix
ORDER BY "Gross Profit" DESC;




